"""Render Codex CODEX_HOME/config.toml for container reviews via model-proxy (M3)."""

from __future__ import annotations

import os

DEFAULT_MODEL_PROXY_BASE_URL = "http://model-proxy:8081/v1"


def model_proxy_base_url() -> str:
    """Upstream base_url written into config.toml (compose DNS)."""
    raw = (os.environ.get("OPR_MODEL_PROXY_BASE_URL") or DEFAULT_MODEL_PROXY_BASE_URL).strip()
    return raw.rstrip("/") or DEFAULT_MODEL_PROXY_BASE_URL


def render_opr_proxy_config(*, base_url: str | None = None) -> str:
    """Return config.toml text: custom ``opr_proxy`` provider + sandbox shell policy.

    Codex 0.164.0: custom ``model_providers`` with ``wire_api = "responses"`` and
    ``supports_websockets = false`` routes ``POST /v1/responses`` SSE to the proxy
    (see ``scripts/spike_m3_proxy/FINDINGS.md``). No separate reliable knob was
    found to disable the built-in chatgpt.com model-catalog fetch; the custom
    provider avoided that path in the spike. Defense in depth: review containers
    use the internal-only ``review_egress`` network (no internet).
    """
    url = (base_url if base_url is not None else model_proxy_base_url()).rstrip("/")
    # Keep shell_environment_policy aligned with docker/review/policy/config.toml.
    return (
        "# Generated by autoreview-bot launcher for model-proxy (M3).\n"
        "# Job token is CODEX_API_KEY in the process env (env_key below); never embed secrets here.\n"
        'model_provider = "opr_proxy"\n'
        "\n"
        "[model_providers.opr_proxy]\n"
        'name = "OPR model proxy"\n'
        f'base_url = "{url}"\n'
        'env_key = "CODEX_API_KEY"\n'
        'wire_api = "responses"\n'
        "supports_websockets = false\n"
        "\n"
        "[shell_environment_policy]\n"
        'inherit = "core"\n'
        "ignore_default_excludes = false\n"
        "\n"
        "[shell_environment_policy.set]\n"
        'LANG = "C.UTF-8"\n'
        'TERM = "dumb"\n'
        "\n"
        "[analytics]\n"
        "enabled = false\n"
    )
